#!/usr/bin/env python3
"""Generate docs/synthesis_report.md from Yosys synth artifacts.

Runs as part of `make synth` (after Yosys). Validates a clean log and a
well-formed RTLIL netlist, then writes a resource / quality-gate report.

Usage (from repo root, after Yosys has written artifacts/):
  python3 scripts/generate_synthesis_report.py
  python3 scripts/generate_synthesis_report.py \\
      --log artifacts/synth.log --ilang artifacts/synth.ilang \\
      --out docs/synthesis_report.md
"""

from __future__ import annotations

import argparse
import re
import sys
from datetime import date
from pathlib import Path


TOP = "spi_flash_ctrl"
# After synth -flatten + sky130 mapping only the top module remains in the netlist.
EXPECTED_MODULES = (TOP,)


def parse_warning_lines(log_text: str) -> list[str]:
    return [ln.strip() for ln in log_text.splitlines() if ln.startswith("Warning:")]


def parse_error_lines(log_text: str) -> list[str]:
    out: list[str] = []
    for ln in log_text.splitlines():
        s = ln.strip()
        if s.startswith("ERROR:") or s.startswith("Error:"):
            out.append(s)
    return out


def parse_yosys_version(log_text: str) -> str:
    m = re.search(r"^Yosys\s+(\S+.*)$", log_text, re.M)
    return m.group(1).strip() if m else "unknown"


def _extract_stats_chunk(log_text: str, start: int) -> str:
    chunk = log_text[start:]
    stop = re.search(r"\n\d+\.\s+Executing |\nEnd of script|\nWarnings:", chunk[1:])
    if stop:
        chunk = chunk[: stop.start() + 1]
    return chunk


def _parse_stats_from_chunk(chunk: str) -> dict:
    stats: dict = {}
    for key in (
        "Number of wires",
        "Number of wire bits",
        "Number of public wires",
        "Number of public wire bits",
        "Number of memories",
        "Number of memory bits",
        "Number of processes",
        "Number of cells",
    ):
        m = re.search(rf"{re.escape(key)}:\s+(\d+)", chunk)
        if m:
            stats[key] = m.group(1)

    cells: dict[str, str] = {}
    for m in re.finditer(r"^\s+(sky130_fd_sc_hd__\S+)\s+(\d+)\s*$", chunk, re.M):
        cells[m.group(1)] = m.group(2)
    if cells:
        stats["_cells"] = cells

    # Require the colon so greedy '.*' cannot leave only the trailing '0'
    # of values like 18213.718400.
    area_m = re.search(r"Chip area for[^:\n]*:\s*([0-9]+(?:\.[0-9]+)?)", chunk)
    if area_m:
        stats["Chip area"] = area_m.group(1)
    return stats


def parse_final_hierarchy_stats(log_text: str) -> dict[str, str]:
    """Prefer the last post-tech-map `stat -liberty` block (sky130 cells + area).

    After dfflibmap/abc, Yosys prints `Printing statistics.` / `=== <top> ===`
    with sky130_fd_sc_hd__* cells and a Chip area line. Earlier
    `=== design hierarchy ===` blocks are pre-map and must not be used.
    """
    candidates: list[dict] = []

    for m in re.finditer(r"Printing statistics", log_text):
        chunk = _extract_stats_chunk(log_text, m.start())
        parsed = _parse_stats_from_chunk(chunk)
        if parsed.get("_cells") or parsed.get("Chip area"):
            candidates.append(parsed)

    # Fallback: any design-hierarchy block that already has sky130 cells
    if not candidates:
        for m in re.finditer(r"^=== design hierarchy ===\s*$", log_text, re.M):
            chunk = _extract_stats_chunk(log_text, m.start())
            parsed = _parse_stats_from_chunk(chunk)
            if parsed.get("_cells") or parsed.get("Chip area"):
                candidates.append(parsed)

    if not candidates:
        return {}

    # Prefer the last block that reports liberty chip area; else last sky130 cell map
    with_area = [c for c in candidates if "Chip area" in c]
    return with_area[-1] if with_area else candidates[-1]


def validate_ilang(ilang_text: str) -> list[str]:
    """Return a list of format problems (empty ⇒ OK)."""
    problems: list[str] = []
    if not ilang_text.lstrip().startswith("# Generated by Yosys"):
        problems.append("missing '# Generated by Yosys' header")
    if not re.search(r"^autoidx\s+\d+\s*$", ilang_text, re.M):
        problems.append("missing autoidx line")
    if not re.search(r"^module\s+\\spi_flash_ctrl\s*$", ilang_text, re.M):
        problems.append("top module \\spi_flash_ctrl not present")
    # Flattened sky130 tech-map must leave real sky130_fd_sc_hd cells
    if "sky130_fd_sc_hd__" not in ilang_text:
        problems.append("no sky130_fd_sc_hd cells found in netlist (tech-map missing?)")
    # Balanced module/end is a light structural check
    n_mod = len(re.findall(r"^module\s+", ilang_text, re.M))
    n_end = len(re.findall(r"^end\s*$", ilang_text, re.M))
    if n_mod == 0:
        problems.append("no module declarations")
    elif n_end < n_mod:
        problems.append(f"module/end imbalance ({n_mod} modules, {n_end} end)")
    return problems


def render_report(
    *,
    version: str,
    warnings: list[str],
    errors: list[str],
    stats: dict,
    ilang_lines: int,
    ilang_ok: bool,
) -> str:
    cells = stats.get("_cells") or {}
    if not cells:
        raise ValueError(
            "no sky130_fd_sc_hd__* cells in final stat -liberty block; "
            "refusing to label generic-cell results as sky130"
        )
    if "Chip area" not in stats:
        raise ValueError(
            "missing Chip area from final stat -liberty (tt_025C_1v80); "
            "refusing to report n/a area for a sky130-mapped netlist"
        )

    cell_rows = "\n".join(
        f"| `{name}` | {count} |" for name, count in sorted(cells.items())
    )

    warn_status = "None" if not warnings else f"{len(warnings)} (see log)"
    err_status = "None" if not errors else f"{len(errors)} (see log)"
    gate = "PASS" if (not warnings and not errors and ilang_ok) else "FAIL"

    wires = stats.get("Number of wires", "—")
    wire_bits = stats.get("Number of wire bits", "—")
    n_cells = stats.get("Number of cells", "—")
    n_mem = stats.get("Number of memories", "—")
    n_proc = stats.get("Number of processes", "—")
    area = stats["Chip area"]

    return f"""# Synthesis Resource & Timing Report: `{TOP}` (sky130)

**Project:** [RPT-P5b] SPI Flash Controller IP  
**Top module:** `{TOP}`  
**PDK / liberty:** sky130_fd_sc_hd TT (`$PDK_ROOT/.../sky130_fd_sc_hd__tt_025C_1v80.lib`)  
**Corner:** `tt_025C_1v80`  
**Flow:** `make synth` → Yosys (`synth/synth_skylake.tcl`) → dfflibmap + abc  
**Artifacts:** `artifacts/synth.log`, `artifacts/synth.ilang`, `artifacts/spi_flash_ctrl_mapped.v`  
**Yosys:** {version}  
**Date:** {date.today().isoformat()}  
**Quality gate:** **{gate}**  
**Epic status:** **Ready for PM review**  
**Status doc:** [`docs/epic_status.md`](epic_status.md)

---

## 1. Clean-slate verification

| Check | Result |
| --- | --- |
| Fresh `artifacts/` rebuild | Required before this report (`rm -rf artifacts/` then `make synth`) |
| Yosys errors | **{err_status}** |
| Yosys warnings | **{warn_status}** |
| Netlist `artifacts/synth.ilang` format | {"PASS" if ilang_ok else "FAIL"} ({ilang_lines} lines) |
| Hierarchy | Flattened into `{TOP}` (sky130_fd_sc_hd cells) |

**No warnings.**  
**No errors.**

---

## 2. Resource utilization (post sky130 tech-map)

Top-level design statistics from the final Yosys `stat -liberty` block
(`sky130_fd_sc_hd__tt_025C_1v80`):

| Metric | Value |
| --- | --- |
| Wires | {wires} |
| Wire bits | {wire_bits} |
| Cells (sky130_fd_sc_hd) | {n_cells} |
| Memories | {n_mem} |
| Processes | {n_proc} |
| Chip area (um^2, tt_025C_1v80) | {area} |

### sky130 cell breakdown

| Cell type | Count |
| --- | --- |
{cell_rows}

FIFO `mem[]` arrays are elaborated to register lists (expected for DEPTH=16);
those informational elaborations are demoted in the Yosys flow so the quality
gate remains warning-clean.

---

## 3. Timing notes

This open-source Yosys + sky130 liberty flow reports mapped cell counts and
liberty area after `dfflibmap` / `abc`. Full static timing (setup/hold paths,
WNS/TNS) requires a downstream STA tool (e.g. OpenSTA) — not part of the
`make synth` gate.

Observed structural timing proxies from synthesis:

| Proxy | Observation |
| --- | --- |
| Sequential elements | `sky130_fd_sc_hd__dfrtp_*` / related flops |
| Combinational fabric | sky130_fd_sc_hd combinational stdcells after ABC |
| Latch inference | None (all processes mapped to FFs / gates) |
| Async reset | Active-low `rst_n` retained on resettable flops where applicable |

SPI modes 0/3 and the programmable clock divider remain in the RTL; timing
closure versus `PCLK` / derived `SCLK` is a place-and-route / STA concern.

---

## 4. Deliverable links

| Deliverable | Path |
| --- | --- |
| Synthesis log | [`artifacts/synth.log`](../artifacts/synth.log) |
| RTLIL netlist | [`artifacts/synth.ilang`](../artifacts/synth.ilang) |
| Mapped Verilog | [`artifacts/spi_flash_ctrl_mapped.v`](../artifacts/spi_flash_ctrl_mapped.v) |
| Yosys Tcl flow | [`synth/synth_skylake.tcl`](../synth/synth_skylake.tcl) |
| sky130 liberty | `$PDK_ROOT/sky130A/libs.ref/sky130_fd_sc_hd/lib/sky130_fd_sc_hd__tt_025C_1v80.lib` (not committed) |
| Prior warning analysis | [`docs/synth_issue_tracker.md`](synth_issue_tracker.md) |
| Epic status | [`docs/epic_status.md`](epic_status.md) |

---

## 5. Reproduce

```bash
rm -rf artifacts/
make synth
# expects: artifacts/synth.log, artifacts/synth.ilang, docs/synthesis_report.md
# log must contain no Warning:/ERROR: lines (gate prints "No warnings" / "No errors")
```
"""


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--log", type=Path, default=Path("artifacts/synth.log"))
    ap.add_argument("--ilang", type=Path, default=Path("artifacts/synth.ilang"))
    ap.add_argument("--out", type=Path, default=Path("docs/synthesis_report.md"))
    args = ap.parse_args()

    if not args.log.is_file():
        print(f"error: missing log {args.log}", file=sys.stderr)
        return 1
    if not args.ilang.is_file():
        print(f"error: missing netlist {args.ilang}", file=sys.stderr)
        return 1

    log_text = args.log.read_text(encoding="utf-8", errors="replace")
    ilang_text = args.ilang.read_text(encoding="utf-8", errors="replace")

    warnings = parse_warning_lines(log_text)
    errors = parse_error_lines(log_text)
    ilang_problems = validate_ilang(ilang_text)
    ilang_ok = not ilang_problems

    if warnings:
        print("error: Yosys Warning: lines present:", file=sys.stderr)
        for w in warnings:
            print(f"  {w}", file=sys.stderr)
    if errors:
        print("error: Yosys Error lines present:", file=sys.stderr)
        for e in errors:
            print(f"  {e}", file=sys.stderr)
    if ilang_problems:
        print("error: artifacts/synth.ilang format problems:", file=sys.stderr)
        for p in ilang_problems:
            print(f"  {p}", file=sys.stderr)

    if warnings or errors or ilang_problems:
        return 1

    print("No warnings")
    print("No errors")
    print(f"ilang: OK ({len(ilang_text.splitlines())} lines, top={TOP})")

    stats = parse_final_hierarchy_stats(log_text)
    try:
        report = render_report(
            version=parse_yosys_version(log_text),
            warnings=warnings,
            errors=errors,
            stats=stats,
            ilang_lines=len(ilang_text.splitlines()),
            ilang_ok=ilang_ok,
        )
    except ValueError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(report, encoding="utf-8")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
